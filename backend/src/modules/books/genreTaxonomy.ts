/** Нормализация: trim → lower → убрать хвостовые запятые → схлопнуть пробелы. */
function normalize(raw: string): string {
  return raw.trim().toLowerCase().replace(/,+$/, "").replace(/\s+/g, " ");
}

function matchSynonyms(raw: string, syns: string[]): boolean {
  const n = normalize(raw);
  return syns.some((s) => normalize(s) === n);
}

/** Строка жанра книги → уникальные CategoryId (неопознанное отбрасывается). */
export function parseBookGenre(genre: string | null | undefined): CategoryId[] {
  if (!genre) return [];
  const ids = new Set<CategoryId>();
  for (const part of genre.split(",")) {
    if (!normalize(part)) continue;
    for (const [id, syns] of Object.entries(GENRE_SYNONYMS)) {
      if (matchSynonyms(part, syns)) ids.add(id as CategoryId);
    }
  }
  return [...ids];
}

/** Тег книги → CategoryId | null. */
export function tagToCategoryId(tag: string): CategoryId | null {
  for (const [id, syns] of Object.entries(TAG_SYNONYMS)) {
    if (matchSynonyms(tag, syns)) return id as CategoryId;
  }
  return null;
}

export function isCategoryId(value: string): value is CategoryId {
  return GENRE_CATEGORIES.some((c) => c.id === value);
}
