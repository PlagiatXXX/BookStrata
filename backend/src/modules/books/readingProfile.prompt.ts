// backend/src/modules/books/readingProfile.prompt.ts
// Промпт для генерации Reading DNA (readingProfile) через AI.
// Используется оператором: копирует промпт → вставляет в ChatGPT/Claude →
// вставляет JSON ответ в админку (PATCH /api/admin/books/:id).

interface BookMetadata {
  title: string;
  author: string | null;
  description: string | null;
  genre: string | null;
  tags: string[];
}

/** Генерирует промпт для AI-разметки readingProfile. */
export function buildReadingProfilePrompt(book: BookMetadata): string {
  return `Ты — литературный аналитик. Оцени книгу по 6 осям Reading DNA.

Оценка попадёт в систему подбора книг: читатель задаёт ожидания по этим же
осям, и ему предлагаются книги с максимальным совпадением. Поэтому важна
честность, а не «красивые» цифры.

Книга: «${book.title}»${book.author ? ` — ${book.author}` : ""}
Жанр: ${book.genre ?? "не указан"}
Теги: ${book.tags.length > 0 ? book.tags.join(", ") : "нет"}
Описание: ${book.description ?? "нет"}

---

ОЦЕНИ ПО ШЕСТИ ОСЯМ (0–100):

01. storyFocus (Сюжет ↔ Рефлексия)
  0–20 — чистый экшн. Погони, интриги, twist за twist.
  20–40 — сюжет ведёт, но есть место для дыхания.
  40–60 — баланс. События и внутренний мир чередуются.
  60–80 — рефлексия доминирует. События — повод для размышлений.
  80–100 — чистая интроспекция. Поток сознания, эссеистика.

02. emotionalWeight (Легко ↔ Тяжело)
  0–20 — воздушное чтиво. Комедия, уют, лёгкость.
  20–40 — мягкое. Есть грусть, но без надавливания.
  40–60 — средний вес. Бывают и радость, и боль.
  60–80 — тяжело. Боль, потеря, экзистенциальный кризис.
  80–100 — надрыв. Катарсис через страдание.

03. pace (Быстро ↔ Погружение)
  0–20 — стрелочная скорость. Главы по 5 страниц.
  20–40 — быстрое чтение. Динамичное, но не истеричное.
  40–60 — размеренное. Средний темп.
  60–80 — неторопливое. Длинные описания, паузы.
  80–100 — медитативное. Каждое предложение — мир.

04. darkness (Светло ↔ Мрачно)
  0–20 — максимально светлое. Надежда, добро, порядок.
  20–40 — преимущественно тёплое. Есть тревога, но свет побеждает.
  40–60 — нейтрально-серое. Жизнь как она есть.
  60–80 — преимущественно тёмное. Атмосфера тревоги, одиночества.
  80–100 — максимально тёмное. Безысходность, абсурд, нигилизм.

05. scope (Камерное ↔ Эпическое)
  0–20 — камерное. Одна комната, одна семья, локальный масштаб.
  20–40 — небольшой мир. Узкий круг персонажей, локальный конфликт.
  40–60 — средний масштаб. Несколько локаций, развёрнутый сюжет.
  60–80 — широкий мир. Много персонажей, масштабные события.
  80–100 — эпическое. Галактики, империи, десятки фракций и поколений.

06. complexity (Доступное ↔ Многослойное)
  0–20 — доступное. Простой синтаксис, акцент на динамике, «проглатывается за вечер».
  20–40 — лёгкое чтение. Несложный язык, но интересная подача.
  40–60 — средняя сложность. Есть стилистика, но без перегруза.
  60–80 — многослойное. Богатая стилистика, метафоры, интертекст.
  80–100 — высокая сложность. Модернистская форма, экспериментальный язык.

---

Для каждой оси оцени confidence (0–1):
- 0.9–1.0 — уверенно, достаточно данных
- 0.7–0.8 — вероятно, но есть неопределённость
- 0.5–0.6 — приблизительно, мало данных
- < 0.5 — сложно определить

---

ПРАВИЛА:
- Оценивай ТОЛЬКО по данным: жанр, теги, аннотация. НЕ выдумывай
  факты, которых нет в тексте выше (сюжет, героев, события).
- Помни: тебе доступна аннотация, а не вся книга. Если данных
  для уверенной оценки оси недостаточно — ставь значение по
  аннотации и честно понижай confidence (0.4–0.6).
- Числа — целые, в диапазоне 0–100, без кавычек.
- Не добавляй полей, кроме указанных в шаблоне ответа.

---

ВЕРНИ РОВНО ОДИН JSON-ОБЪЕКТ. Без пояснений до или после.
Без markdown-обёртки — НЕ оборачивай ответ в \`\`\` или \`\`\`json.

{
  "storyFocus": <целое число 0–100>,
  "emotionalWeight": <целое число 0–100>,
  "pace": <целое число 0–100>,
  "darkness": <целое число 0–100>,
  "scope": <целое число 0–100>,
  "complexity": <целое число 0–100>,
  "confidence": {
    "storyFocus": <число 0–1>,
    "emotionalWeight": <число 0–1>,
    "pace": <число 0–1>,
    "darkness": <число 0–1>,
    "scope": <число 0–1>,
    "complexity": <число 0–1>
  },
  "source": "ai"
}`;
}
